export type Glyph = number[]; // 7 rows, each a 5-bit mask (bit 4 = col 0)

function parse(rows: string[]): Glyph {
  return rows.map((r) => {
    let mask = 0;
    for (let c = 0; c < GLYPH_W; c++) {
      if (r[c] === "#") mask |= 1 << (GLYPH_W - 1 - c);
    }
    return mask;
  });
}

const FONT: Record<string, Glyph> = {};
for (const key in RAW) FONT[key] = parse(RAW[key]);

const MISSING: Glyph = FONT["?"];

export function glyphFor(ch: string): Glyph {
  // exact case first (so lowercase renders lowercase), then fall back
  return FONT[ch] ?? FONT[ch.toUpperCase()] ?? MISSING;
}

/** Is pixel (col,row) within a glyph lit? */
export function glyphPixel(g: Glyph, col: number, row: number): boolean {
  return (g[row] & (1 << (GLYPH_W - 1 - col))) !== 0;
}
